"""Run the harness on Kaggle's GPUs from this machine.

    pixi run kg push gpt2 --size s              # package local code, run on a Kaggle T4
    pixi run kg push gpt2 --size s --smoke      # 2M-token sanity run, not recorded
    pixi run kg status gpt2 --size s
    pixi run kg pull gpt2 --size s              # download outputs, record results/gpt2-s.json

The current working tree (harness/, configs/, pyproject.toml) is bundled into a
single script, so nothing needs to be committed or pushed to GitHub first. Each
arch/size pair is one private Kaggle kernel; every push is a new version of it.
"""

import argparse
import base64
import io
import json
import os
import shutil
import subprocess
import sys
import tarfile
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BUNDLE_PATHS = ["harness", "configs", "pyproject.toml"]
ACCELERATOR = "NvidiaTeslaT4"  # every recorded run uses the same GPU
SMOKE_SET = ["train.tokens=2e6", "train.eval_every_tokens=1e6", "train.warmup_tokens=2e5"]

RUNNER = '''\
"""Generated by scripts/kaggle.py -- do not edit; re-run `kg push` instead."""
import base64, io, os, subprocess, sys, tarfile

BUNDLE = {bundle!r}
ARGS = {args!r}
COMMIT = {commit!r}

work = os.environ.get("KAGGLE_WORKING", "/kaggle/working")
dst = os.path.join(work, "arc-to-god")
with tarfile.open(fileobj=io.BytesIO(base64.b64decode(BUNDLE))) as tar:
    tar.extractall(dst)

cmd = [sys.executable, "-m", "harness.train", *ARGS, "--out", os.path.join(work, "runs")]
print("$", " ".join(cmd), flush=True)
env = dict(os.environ, ARC_TO_GOD_COMMIT=COMMIT)
sys.exit(subprocess.run(cmd, cwd=dst, env=env).returncode)
'''


def run(cmd, **kw):
    print("$", " ".join(cmd), flush=True)
    return subprocess.run(cmd, check=True, **kw)


def kaggle_user() -> str:
    if os.environ.get("KAGGLE_USERNAME"):
        return os.environ["KAGGLE_USERNAME"]
    for path in ("~/.kaggle/kaggle.json", "~/.config/kaggle/kaggle.json"):
        path = os.path.expanduser(path)
        if os.path.exists(path):
            with open(path) as f:
                return json.load(f)["username"]
    # Newer token-only setups (~/.kaggle/access_token) have no username on disk; ask the CLI.
    try:
        out = subprocess.check_output(["kaggle", "config", "view"], stderr=subprocess.DEVNULL).decode()
        for line in out.splitlines():
            if line.strip().startswith("- username:"):
                name = line.split(":", 1)[1].strip()
                if name and name != "None":
                    return name
    except (OSError, subprocess.CalledProcessError):
        pass
    sys.exit("No Kaggle credentials. Create a token at kaggle.com > Settings > API and save it to ~/.kaggle/.")


def kernel_slug(arch: str, size: str, smoke: bool) -> str:
    return f"arc-to-god-{arch}-{size}" + ("-smoke" if smoke else "")


def local_commit() -> str:
    try:
        sha = subprocess.check_output(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, stderr=subprocess.DEVNULL).decode().strip()
    except subprocess.CalledProcessError:
        return "uncommitted"
    dirty = subprocess.run(["git", "diff", "--quiet", "HEAD"], cwd=ROOT).returncode != 0
    return sha + ("-dirty" if dirty else "")


def bundle() -> str:
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz") as tar:
        for p in BUNDLE_PATHS:
            tar.add(os.path.join(ROOT, p), arcname=p, filter=lambda ti: None if "__pycache__" in ti.name else ti)
    return base64.b64encode(buf.getvalue()).decode()


def write_runner(path: str, arch: str, size: str, smoke: bool, overrides: list[str]):
    args = [arch, "--size", size, "--set", "data.dir=/tmp/enwik8", *(SMOKE_SET if smoke else []), *overrides]
    if smoke:
        args.append("--no-record")
    with open(path, "w") as f:
        f.write(RUNNER.format(bundle=bundle(), args=args, commit=local_commit()))


def cmd_push(a):
    user = kaggle_user()
    slug = kernel_slug(a.arch, a.size, a.smoke)
    with tempfile.TemporaryDirectory() as tmp:
        write_runner(os.path.join(tmp, "run.py"), a.arch, a.size, a.smoke, a.set)
        meta = {
            "id": f"{user}/{slug}",
            "title": slug,
            "code_file": "run.py",
            "language": "python",
            "kernel_type": "script",
            "is_private": True,
            "enable_gpu": True,
            "enable_internet": True,  # enwik8 download
            "machine_shape": ACCELERATOR,
        }
        with open(os.path.join(tmp, "kernel-metadata.json"), "w") as f:
            json.dump(meta, f, indent=2)
        run(["kaggle", "kernels", "push", "-p", tmp, "--accelerator", ACCELERATOR])
    print(f"\nRunning at https://www.kaggle.com/code/{user}/{slug}\nCheck with: pixi run kg status {a.arch} --size {a.size}" + (" --smoke" if a.smoke else ""))


def cmd_status(a):
    run(["kaggle", "kernels", "status", f"{kaggle_user()}/{kernel_slug(a.arch, a.size, a.smoke)}"])


def cmd_pull(a):
    slug = kernel_slug(a.arch, a.size, a.smoke)
    out = os.path.join(ROOT, "runs", "kaggle", slug)
    if os.path.exists(out):
        shutil.rmtree(out)
    os.makedirs(out)
    run(["kaggle", "kernels", "output", f"{kaggle_user()}/{slug}", "-p", out])

    found = [os.path.join(d, "results.json") for d, _, files in os.walk(out) if "results.json" in files and os.sep + "runs" + os.sep in d + os.sep]
    if not found:
        sys.exit(f"No results.json in {out}; the run may have failed. See the .log file there.")
    latest = max(found, key=os.path.getmtime)
    with open(latest) as f:
        r = json.load(f)
    print(f"\n{r['arch']}-{r['size']} on {r['device']}: val_bpc={r['val_bpc']:.4f} test_bpc={r['test_bpc']:.4f} "
          f"copy_bpc={r['copy_bpc']:.4f} tok/s={r['train_tokens_per_s']:.0f}")
    if a.smoke:
        print("(smoke run, not recorded)")
        return
    os.makedirs(os.path.join(ROOT, "results"), exist_ok=True)
    dst = os.path.join(ROOT, "results", f"{r['arch']}-{r['size']}.json")
    shutil.copy(latest, dst)
    print(f"recorded -> {os.path.relpath(dst, ROOT)}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    for name, fn in (("push", cmd_push), ("status", cmd_status), ("pull", cmd_pull)):
        p = sub.add_parser(name)
        p.add_argument("arch")
        p.add_argument("--size", default="s")
        p.add_argument("--smoke", action="store_true")
        if name == "push":
            p.add_argument("--set", nargs="*", default=[], metavar="KEY=VALUE")
        p.set_defaults(fn=fn)
    a = ap.parse_args()
    a.fn(a)


if __name__ == "__main__":
    main()
